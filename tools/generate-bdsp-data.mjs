// Generate both consumers from the same pinned PokeFinder resources.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../third_party/PokeFinder/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('manifest.json', root), 'utf8'));
for (const [file, hash] of Object.entries(manifest.hashes)) {
  if (createHash('sha256').update(readFileSync(new URL(file, root))).digest('hex') !== hash) throw Error(`Upstream file changed: ${file}`);
}
const read = file => readFileSync(new URL(file, root), 'utf8');
const strings = name => read(`Core/Resources/i18n/zh/${name}_zh.txt`).trim().split(/\r?\n/);
const encounters = JSON.parse(read('Core/Resources/EncounterTables/Gen8/encounters.json'));
const binary = readFileSync(new URL('Core/Resources/Personal/Gen8/personal_bdsp.bin', root));
if (binary.length % 0x44) throw Error('Invalid personal table size');
const species = strings('species');
const targets = Object.entries(encounters).flatMap(([category, rows]) => rows.map(row => ({
  category, speciesKey: row.description, speciesId: row.specie,
  species: row.description === 'Happiny egg' ? '小福蛋蛋' : row.description === 'Riolu egg' ? '利欧路蛋' : species[row.specie - 1],
  version: row.version.replace('Game::', ''), form: row.form ?? 0, level: row.level,
  ability: row.ability ?? 255, shiny: row.shiny === 'Shiny::Never' ? 1 : 0,
  gender: row.gender ?? 255, ivCount: row.ivCount ?? 0, fateful: row.fateful ?? false, roamer: row.roamer ?? false,
})));
const personal = [];
for (let offset = 0; offset < binary.length; offset += 0x44) {
  const byte = i => binary[offset + i];
  const word = i => binary.readUInt16LE(offset + i);
  personal.push(`PersonalInfo({${[0,1,2,4,5,3].map(byte)}}, {${byte(6)},${byte(7)}}, {${word(12)},${word(14)},${word(16)}}, ${byte(18)}, {${word(24)},${word(26)},${word(28)}}, ${byte(32)}, ${word(30)}, ${word(62)}, ${Boolean((byte(33) >> 6) & 1)})`);
}
const formNames = new Map(strings('forms').map(line => {
  const [id, form, ...label] = line.split(',');
  return [`${id}:${form}`, label.join(',')];
}));
const calculatorSpecies = [];
for (let id = 1; id <= 493; id++) {
  const offset = id * 0x44;
  if (!((binary[offset + 0x21] >> 6) & 1)) continue;
  const formCount = Math.max(1, binary[offset + 0x20]);
  const formIndex = binary.readUInt16LE(offset + 0x1e);
  calculatorSpecies.push({ id, name: species[id - 1], forms: Array.from({ length: formCount }, (_, form) => {
    const index = form && formIndex ? formIndex + form - 1 : id;
    if ((index + 1) * 0x44 > binary.length) throw Error(`Invalid form index: ${id}:${form}`);
    return { id: form, name: formNames.get(`${id}:${form}`) ?? String(form), stats: [0,1,2,4,5,3].map(i => binary[index * 0x44 + i]) };
  }) });
}
const data = { revision: manifest.revision, targets, calculatorSpecies, natures: strings('natures'), characteristics: strings('characteristic'), abilities: strings('abilities'), hiddenPowers: strings('powers') };
const generated = new URL('../src/generated/', import.meta.url);
function emit(file, contents) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== contents) writeFileSync(file, contents);
}
mkdirSync(generated, { recursive: true });
emit(new URL('bdsp-data.json', generated), JSON.stringify(data, null, 2) + '\n');
const native = new URL('../runtime/generated/', import.meta.url);
mkdirSync(native, { recursive: true });
emit(new URL('bdsp_data.hpp', native), '// Generated by tools/generate-bdsp-data.mjs; do not edit. GPL-3.0-or-later upstream data.\n#pragma once\n#include <Core/Parents/PersonalInfo.hpp>\n#include <array>\n' +
  `inline constexpr std::array<PersonalInfo, ${personal.length}> bdsp_personal = {\n${personal.join(',\n')}\n};\n` +
  `inline constexpr char bdsp_targets_json[] = R"BDSP(${JSON.stringify(targets)})BDSP";\n`);
console.log(`Generated ${targets.length} encounters and ${personal.length} personal records from PokeFinder ${manifest.version}`);
