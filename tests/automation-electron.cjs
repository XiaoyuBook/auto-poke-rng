const {app,BrowserWindow,ipcMain,safeStorage,nativeImage}=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {registerDevices}=require('../electron/devices.cjs');
const {registerBlink}=require('../electron/blink-client.cjs');
const {registerRng}=require('../electron/rng-client.cjs');
const {registerAutomation}=require('../electron/automation.cjs');
const {startWorker}=require('../electron/automation-worker.cjs');
const {registerScriptFiles}=require('../electron/script-files.cjs');
const {registerPanelWindows}=require('../electron/panel-windows.cjs');
const {registerQQNotifications}=require('../electron/qq-notifications.cjs');
const root=path.resolve(__dirname,'..'),output=path.join(root,'node_modules/.tmp/automation-review');
fs.mkdirSync(output,{recursive:true});app.setPath('userData',fs.mkdtempSync(path.join(output,'profile-')));
app.commandLine.appendSwitch('disable-gpu');
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let devices,blink,rng,automation,notifications;
const timer=setTimeout(()=>{console.error('Automation Electron test timed out');app.exit(1);},55000);
app.whenReady().then(async()=>{
  const main=new BrowserWindow({width:1500,height:940,show:false,webPreferences:{preload:path.join(root,'electron/preload.cjs'),contextIsolation:true,sandbox:true,backgroundThrottling:false}});
  const js=async code=>{try{return await main.webContents.executeJavaScript(code,true);}catch(error){throw Error(`${error.message}\nExpression: ${code}`);}};
  const until=async(code,name)=>{for(let i=0;i<180;i++){if(await js(code))return;await delay(30);}throw Error(name);};
  const click=text=>js(`Array.from(document.querySelectorAll('button')).find(x=>x.textContent===${JSON.stringify(text)}&&x.getClientRects().length).click()`);
  const screenshot=async name=>{await delay(150);fs.writeFileSync(path.join(output,name),(await main.webContents.capturePage()).toPNG());console.log('Rendered',name);};
  const loadWindow=(window,query={})=>window.loadFile(path.join(root,'dist/index.html'),{query});
  ipcMain.handle('app:metadata',()=>({name:'Auto Poke RNG',version:'test',platform:'win32'}));
  registerPanelWindows({getMainWindow:()=>main,loadWindow});
  registerScriptFiles({getMainWindow:()=>main,rootDirectory:path.join(root,'scripts')});
  devices=registerDevices({ipcMain,getWindows:()=>BrowserWindow.getAllWindows(),rootDirectory:path.join(root,'scripts'),testMode:true});
  rng=registerRng({ipcMain,getMainWindow:()=>main,isAutomationBusy:()=>devices.isAutomationBusy()});
  blink=registerBlink({ipcMain,getMainWindow:()=>main,getVideo:()=>devices.getState().video,isAutomationBusy:()=>devices.isAutomationBusy()});
  notifications=registerQQNotifications({ipcMain,getMainWindow:()=>main,safeStorage,nativeImage,userData:app.getPath('userData')});
  automation=registerAutomation({ipcMain,getMainWindow:()=>main,getWindows:()=>BrowserWindow.getAllWindows(),devices,rng,blink,userData:app.getPath('userData'),
    workerFactory:(config,callbacks)=>{
      if(config.command)return startWorker(config,callbacks);
      let resolve;const done=new Promise(r=>{resolve=r;});
      queueMicrotask(()=>{
        callbacks.event({event:'history',name:'cycle_start',args:[1]});
        callbacks.event({event:'history',name:'seed_captured',args:['123456789ABCDEF0 1111111122222222',0]});
        callbacks.event({event:'history',name:'candidates_found',args:[[{advances:1800,pid:17,ec:23,ivs:[31,0,31,31,31,31],stats:[100,50,80,90,80,100],ability:0,gender:0,nature:3,shiny:2,height:128,weight:64,characteristic:0}],0,['sync']]});
        callbacks.event({event:'progress',clock:1,wall:1000,progress:{phase:'等待触发',loop_index:1,current_advances:0,raw_target_advances:1800,trigger_advances:340,log_message:'测试轮次就绪'}});
        callbacks.event({event:'log',message:'自动流程测试日志'});
      });
      return {done,send:()=>{},stop:async()=>resolve({status:'stopped',message:'用户停止'})};
    }});
  await loadWindow(main);
  main.showInactive();
  await until(`Boolean(document.querySelector('[aria-label^="切换游戏"]'))`,'app ready');
  await js(`document.querySelector('[aria-label^="切换游戏"]').click()`);
  await until(`Boolean(document.querySelector('[role=menuitemradio]'))`,'game picker');
  await js(`Array.from(document.querySelectorAll('[role=menuitemradio]')).find(x=>x.textContent.includes('珍钻复刻')).click()`);
  await click('自动定点');
  await until(`Boolean(document.querySelector('[aria-label="自动定点工作区"] input[aria-label="基准 delay"]'))`,'automation page');
  const ready=await js(`(async()=>window.desktop.automation.check({kind:'static',config:(await window.desktop.automation.getState()).config.static,blink:{},profile:{version:'BD',tid:0,sid:0}}))()`);
  assert.equal(ready.ready,false);assert.equal(automation.getState().runs.length,0);
  await js(`(()=>{const input=document.querySelector('[aria-label="基准 delay"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'1442');input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  await click('保存任务参数');
  await until(`document.querySelector('[aria-label="自动定点工作区"]').textContent.includes('任务参数已保存')`,'parameter save');
  await click('自动TID');await click('自动定点');assert.equal(await js(`document.querySelector('[aria-label="基准 delay"]').value`),'1442');
  await screenshot('automatic-static.png');
  // Device integration stays on synthetic video and the mock controller.
  await js(`window.desktop.devices.video.connect({deviceId:'synthetic',backend:'msmf',width:640,height:480,fps:60})`);
  await until(`document.querySelector('.live-video')?.naturalWidth===640`,'synthetic video');
  await js(`window.desktop.devices.controller.connect('mock')`);
  const input={kind:'static',config:automation.getState().config.static,profile:{version:'BD',tid:0,sid:0},blink:{sourceWidth:640,sourceHeight:480,eye:'data:image/png;base64,AQ==',roi:{x:0,y:0,width:20,height:20},threshold:.9,npc:0,noisy:false,seed:['1','2','3','4'],searchMin:0,searchMax:1000000}};
  input.config.parameters.start='capture';input.config.parameters.shiny_threshold_seconds=null;
  input.config.scripts={...input.config.scripts,advance:'BDSP/bdsp过帧.rng',hit:'BDSP/御三家撞帧.rng'};
  await js(`window.desktop.automation.start(${JSON.stringify(input)})`);
  await until(`document.querySelector('[aria-label="自动定点工作区"]').textContent.includes('测试轮次就绪')`,'runtime state broadcast');
  assert.equal(await js(`window.desktop.devices.controller.press('A').then(()=>false,()=>true)`),true,'manual input blocked');
  await click('查看相关日志');
  await until(`document.querySelector('.floating-panel')?.textContent.includes('自动流程测试日志') || document.querySelector('.automation-log-center')?.textContent.includes('自动流程测试日志')`,'related logs');
  await screenshot('log-center.png');
  await js(`window.desktop.panels.open('logs')`);
  const detached=BrowserWindow.getAllWindows().find(window=>window!==main&&window.webContents.getURL().includes('panel=logs'));
  assert.ok(detached,'detached log window created');
  await delay(200);
  assert.ok(await detached.webContents.executeJavaScript(`document.body.textContent.includes('自动流程测试日志')`),'detached logs share backend state');
  await js(`window.desktop.automation.stop()`);assert.equal(automation.getState().state.status,'stopped');
  assert.equal(devices.isAutomationBusy(),false);
  await detached.webContents.executeJavaScript(`window.desktop.automation.clearLogs()`);
  assert.equal(automation.getState().logs.length,0);
  await detached.webContents.executeJavaScript(`void window.desktop.panels.dock();true`);
  await delay(100);
  await js(`document.querySelector('[aria-label="关闭日志中心"]')?.click()`);
  await click('自动TID');
  const ids=await js(`window.desktop.automation.tidPreview({seed:['40000000','00000000','40000000','00000000'],frame_threshold:4})`);
  assert.deepEqual(ids.id_states.map(row=>row.advances),[0,1,2,3,4]);
  await screenshot('automatic-tid.png');
  await click('闪光反查区域');
  await until(`Boolean(document.querySelector('[aria-label="闪光反查区域工作区"]'))`,'OCR page');
  assert.equal(await js(`document.querySelectorAll('.ocr-table tbody tr').length`),10);
  await screenshot('ocr-settings.png');
  assert.ok(fs.readdirSync(path.join(app.getPath('userData'),'logs')).length,'daily disk log exists after clearing');
  console.log('PASS: automation navigation, saved drafts, real IPC, input exclusion, related/detached logs, stop, ID worker and OCR settings');
}).catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  clearTimeout(timer);await automation?.close();notifications?.close();await Promise.allSettled([devices?.close(),blink?.close(),rng?.close()]);app.exit(process.exitCode||0);
});
