const { app, BrowserWindow, ipcMain, safeStorage, nativeImage } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { registerRng } = require('../electron/rng-client.cjs');
const { registerDevices } = require('../electron/devices.cjs');
const { registerPanelWindows } = require('../electron/panel-windows.cjs');
const { registerScriptFiles } = require('../electron/script-files.cjs');
const { registerQQNotifications } = require('../electron/qq-notifications.cjs');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'node_modules/.tmp/pokefinder-review');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', fs.mkdtempSync(path.join(output, 'profile-')));
app.commandLine.appendSwitch('disable-gpu');
let rng, devices, notifications;
const timeout = setTimeout(() => { console.error('PokeFinder Electron test timed out'); app.exit(1); }, 45000);
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const js = (window, code) => window.webContents.executeJavaScript(code, true);
async function until(window, code, label) {
  for (let i = 0; i < 150; i++) { if (await js(window, code)) return; await delay(30); }
  throw Error(label);
}
app.whenReady().then(async () => {
  ipcMain.handle('app:metadata', () => ({ name: 'Auto Poke RNG', version: 'test', platform: 'win32' }));
  const main = new BrowserWindow({ width: 1600, height: 1000, show: false, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } });
  const loadWindow = (window, query = {}) => window.loadFile(path.join(root, 'dist/index.html'), { query });
  registerPanelWindows({ getMainWindow: () => main, loadWindow });
  const scriptRoot = fs.mkdtempSync(path.join(output, 'scripts-'));
  registerScriptFiles({ getMainWindow: () => main, rootDirectory: scriptRoot });
  devices = registerDevices({ ipcMain, getWindows: () => BrowserWindow.getAllWindows(), rootDirectory: scriptRoot, testMode: true });
  rng = registerRng({ ipcMain, getMainWindow: () => main });
  notifications = registerQQNotifications({ ipcMain, getMainWindow: () => main, safeStorage, nativeImage, userData: app.getPath('userData') });
  await loadWindow(main);
  main.showInactive();
  await until(main, 'Boolean(document.querySelector(\'[aria-label^="切换游戏"]\'))', 'app ready');
  const request = { seed0: '1234567887654321', seed1: '8765432112345678', initialAdvances: 0, maxAdvances: 0, offset: 0, lead: 255, target: 'Turtwig', profile: { version: 'BD', tid: 12345, sid: 54321 }, filter: {} };
  const direct = await js(main, `window.desktop.rng.staticGenerate(${JSON.stringify(request)})`);
  assert.equal(direct[0].ec, '220345D0');
  assert.deepEqual(direct[0].stats, [20,12,12,11,12,8]);
  await js(main, `document.querySelector('[aria-label^="切换游戏"]').click()`);
  await js(main, `Array.from(document.querySelectorAll('[role="menuitemradio"]')).find(x=>x.textContent.includes('珍钻复刻')).click()`);
  const clickText = async text => js(main, `Array.from(document.querySelectorAll('dialog[open] button, body:not(:has(dialog[open])) button')).find(x=>x.textContent===${JSON.stringify(text)}).click()`);
  const setInput = async (label, value) => js(main, `(() => { const input = document.querySelector('dialog[open] [aria-label=${JSON.stringify(label)}]') || document.querySelector('[aria-label=${JSON.stringify(label)}]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await js(main, `document.querySelector('[title="首页"]').click()`);
  await clickText('管理');
  await setInput('存档名称', '测试存档'); await setInput('TID', '42');
  await clickText('取消');
  assert.equal(await js(main, `document.querySelector('[aria-label="TID"]').value`), '12345');
  await clickText('管理');
  await setInput('存档名称', '测试存档');
  await delay(150);
  fs.writeFileSync(path.join(output, 'profile-management.png'), (await main.webContents.capturePage()).toPNG());
  await clickText('保存并应用');
  assert.equal(await js(main, `JSON.parse(localStorage.getItem('auto-poke-rng:bdsp-profile')).name`), '测试存档');
  await js(main, `document.querySelector('[title="定点数据"]').click()`);
  await until(main, `Boolean(document.querySelector('[aria-label="Seed 0"]'))`, 'static workspace ready');
  main.setSize(1500, 900); await delay(150);
  fs.writeFileSync(path.join(output, 'compact-empty-1500.png'), (await main.webContents.capturePage()).toPNG());
  assert.equal(await js(main, `(() => { const card=document.querySelector('.static-config-card'); return card.scrollHeight<=card.clientHeight+1; })()`), true, 'all parameters and filters fit without scrolling at a normal workspace width');
  assert.equal(await js(main, `document.querySelector('.static-results-card').getBoundingClientRect().height>=240 && document.querySelector('.static-table-wrap').getBoundingClientRect().height>=180`), true, 'compact settings leave usable result table height');
  main.setSize(1600, 1000); await delay(150);
  await js(main, `window.previewBefore = document.querySelector('.persistent-video'); window.logsBefore = document.querySelector('.persistent-logs');`);
  await setInput('Seed 0', request.seed0); await setInput('Seed 1', request.seed1); await setInput('最大帧数', '0');
  await js(main, `Array.from(document.querySelectorAll('button')).find(x=>x.textContent==='生成').click()`);
  await until(main, `document.querySelector('.static-search-status')?.textContent === '已生成结果'`, 'native results rendered');
  const firstRow = await js(main, `Array.from(document.querySelectorAll('.static-table tbody tr:first-child td')).map(x=>x.textContent)`);
  assert.deepEqual(firstRow, ['0','220345D0','2203506A','否','自大','0','雄','4','23','15','30','19','26','124','99','好奇心强']);
  await js(main, `document.querySelector('.stats-toggle input').click()`);
  assert.deepEqual(await js(main, `Array.from(document.querySelectorAll('.static-table tbody tr:first-child td')).slice(7,13).map(x=>Number(x.textContent))`), direct[0].stats);
  assert.equal(await js(main, `Boolean(window.previewBefore && window.logsBefore) && document.querySelector('.persistent-video') === window.previewBefore && document.querySelector('.persistent-logs') === window.logsBefore`), true);
  await delay(200);
  fs.writeFileSync(path.join(output, 'native-results-wide.png'), (await main.webContents.capturePage()).toPNG());
  main.setSize(1280, 840); await delay(150);
  assert.equal(await js(main, `(() => {
    const tops=['分类','宝可梦','队首'].map(label=>document.querySelector('[aria-label="'+label+'"]').getBoundingClientRect().top);
    return Math.max(...tops)-Math.min(...tops)<1;
  })()`), true, 'target controls stay on the same baseline when their labels move above them');
  fs.writeFileSync(path.join(output, 'compact-results-1280.png'), (await main.webContents.capturePage()).toPNG());
  assert.equal(await js(main, `(() => {
    const card = document.querySelector('.static-config-card').getBoundingClientRect();
    return Array.from(document.querySelectorAll('.static-config-card input,.static-config-card select,.lead-selector-trigger')).every(input=>{const r=input.getBoundingClientRect();return r.left>=card.left && r.right<=card.right;});
  })()`), true, 'all settings fit the left workspace at 1280px');
  assert.equal(await js(main, `(() => {
    const workspace=document.querySelector('.static-workspace').getBoundingClientRect();
    const results=document.querySelector('.static-results-toolbar').getBoundingClientRect();
    return results.top>=workspace.top && results.bottom<=workspace.bottom;
  })()`), true, 'search actions remain visible while settings scroll');
  assert.equal(await js(main, `(() => {
    const card=document.querySelector('.static-config-card');card.scrollTop=card.scrollHeight;
    const r=card.getBoundingClientRect();const input=document.querySelector('[aria-label="体重上限"]').getBoundingClientRect();
    return input.top>=r.top && input.bottom<=r.bottom;
  })()`), true, 'last filter remains reachable in the compact scroll area');
  await js(main, `document.querySelector('.static-config-card').scrollTop=0`);
  await js(main, `new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`);
  assert.equal(await js(main, `Array.from(document.querySelectorAll('[aria-label^="Seed "]')).every(input=>input.scrollWidth<=input.clientWidth)`), true, 'both full 16-digit seeds fit without horizontal scrolling');
  await js(main, `document.querySelector('[aria-label="队首"]').click()`);
  await js(main, `document.querySelector('.lead-selector-menu [aria-haspopup="menu"]').click()`);
  assert.equal(await js(main, `document.querySelectorAll('[aria-label="同步性格"] button').length`), 25);
  assert.equal(await js(main, `(() => { const r=document.querySelector('[aria-label="同步性格"]').getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.top>=0 && r.bottom<=innerHeight;})()`), true);
  await delay(200);
  fs.writeFileSync(path.join(output, 'lead-menu-1280.png'), (await main.webContents.capturePage()).toPNG());
  await js(main, `Array.from(document.querySelectorAll('[aria-label="同步性格"] button')).find(x=>x.textContent==='固执').click()`);
  await js(main, `Array.from(document.querySelectorAll('button')).find(x=>x.textContent==='生成').click()`);
  await until(main, `document.querySelector('.static-table tbody tr td:nth-child(5)')?.textContent==='固执'`, 'synchronize reaches native generator');
  assert.equal(await js(main, `Boolean(document.querySelector('[aria-label="筛选方案"]'))`), false);
  await clickText('表格设置');
  await js(main, `Array.from(document.querySelectorAll('dialog label')).find(x=>x.textContent==='EC').querySelector('input').click()`);
  await delay(150);
  fs.writeFileSync(path.join(output, 'table-columns-1280.png'), (await main.webContents.capturePage()).toPNG());
  await clickText('完成');
  assert.equal(await js(main, `document.querySelectorAll('.static-table th').length`), 15);
  assert.equal(await js(main, `document.querySelector('.static-table td:nth-child(2)').textContent`), direct[0].pid);
  await clickText('表格设置');
  assert.equal(await js(main, `Array.from(document.querySelectorAll('dialog label')).find(x=>x.textContent==='EC').querySelector('input').checked`), false);
  await clickText('显示全部列'); await clickText('完成');
  await clickText('个体值计算器');
  const setSelect = async (label, value) => js(main, `(() => { const input = document.querySelector('dialog [aria-label=${JSON.stringify(label)}]'); input.value=${JSON.stringify(value)}; input.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await setSelect('计算器宝可梦', '492'); await setSelect('计算器性格', '10'); await setSelect('计算器个性', '16'); await setSelect('计算器觉醒力量', '10');
  const ivFixture = require('../third_party/PokeFinder/Test/Util/ivchecker.json').calculateIVRange[0];
  for (let i = 0; i < 3; i++) {
    if (i) await clickText('新增行');
    await setInput(`第 ${i + 1} 行等级`, String(ivFixture.levels[i]));
    for (const [index, label] of ['HP','攻击','防御','特攻','特防','速度'].entries()) await setInput(`第 ${i + 1} 行${label}`, String(ivFixture.stats[i][index]));
  }
  await clickText('计算');
  await until(main, `document.querySelector('dialog [role="status"]')?.textContent==='计算完成'`, 'native IV calculation rendered');
  assert.deepEqual(await js(main, `Array.from(document.querySelectorAll('.iv-calculator-results tbody tr')).map(row=>row.children[2].textContent)`), ['14–19','20–26','14–19','20、22、24、26','1、3、5','31']);
  assert.equal(await js(main, `(() => { const r=document.querySelector('dialog').getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.top>=0 && r.bottom<=innerHeight;})()`), true);
  assert.equal(await js(main, `(() => {
    const button=document.querySelector('.iv-calculator-dialog .bdsp-tool-actions .primary');
    const r=button.getBoundingClientRect();
    return r.top>=0 && r.bottom<=innerHeight && button.contains(document.elementFromPoint(r.left+r.width/2,r.top+r.height/2));
  })()`), true, 'calculator actions remain visible and clickable without scrolling after adding measurements');
  await delay(150);
  fs.writeFileSync(path.join(output, 'iv-calculator-1280.png'), (await main.webContents.capturePage()).toPNG());
  await clickText('关闭');
  assert.equal(await js(main, `document.querySelector('.persistent-video') === window.previewBefore && document.querySelector('.persistent-logs') === window.logsBefore`), true);
  const cancelledRequest = { ...request, maxAdvances: 1000000000, filter: { natures: Array(25).fill(false) } };
  await js(main, `window.cancelResult = window.desktop.rng.staticGenerate(${JSON.stringify(cancelledRequest)}).then(()=>'',error=>error.message); void 0`);
  await js(main, `window.desktop.rng.cancel()`);
  assert.match(await js(main, 'window.cancelResult'), /已取消搜索/);
  assert.equal((await js(main, `window.desktop.rng.staticGenerate(${JSON.stringify(request)})`)).length, 1);
  // Restricted to the primary window, even though the same preload is exposed elsewhere.
  const other = new BrowserWindow({ show: false, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), contextIsolation: true, sandbox: true } });
  await other.loadURL('about:blank');
  await assert.rejects(js(other, `window.desktop.rng.staticGenerate(${JSON.stringify(request)})`), /Unknown RNG sender/);
  await assert.rejects(js(other, `window.desktop.rng.calculateIvs({species:492,entries:[]})`), /Unknown RNG sender/);
  other.destroy();
  console.log('PokeFinder Electron: real search, profile management, column visibility, IV calculator, lead menu, cancellation and sender isolation passed.');
  console.log('Screenshots: ' + output);
  await rng.close(); await devices.close(); notifications.close(); clearTimeout(timeout); app.exit(0);
}).catch(async error => { console.error(error); await rng?.close(); await devices?.close(); notifications?.close(); clearTimeout(timeout); app.exit(1); });
