const { app, BrowserWindow, ipcMain, safeStorage, nativeImage } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { registerDevices } = require('../electron/devices.cjs');
const { registerBlink } = require('../electron/blink-client.cjs');
const { registerRng } = require('../electron/rng-client.cjs');
const { registerAutomation } = require('../electron/automation.cjs');
const { registerScriptFiles } = require('../electron/script-files.cjs');
const { registerPanelWindows } = require('../electron/panel-windows.cjs');
const { registerQQNotifications } = require('../electron/qq-notifications.cjs');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'node_modules/.tmp/automation-groups-review');
fs.mkdirSync(output, { recursive: true });
const userData = fs.mkdtempSync(path.join(output, 'profile-'));
app.setPath('userData', userData);
app.commandLine.appendSwitch('disable-gpu');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
let devices, blink, rng, automation, notifications;
const timer = setTimeout(() => { console.error('Automation groups test timed out'); app.exit(1); }, 30000);

app.whenReady().then(async () => {
  const main = new BrowserWindow({ width: 1500, height: 940, show: false, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), contextIsolation: true, sandbox: true, backgroundThrottling: false } });
  const js = code => main.webContents.executeJavaScript(code, true);
  const until = async (code, label) => { for (let i = 0; i < 150; i++) { if (await js(code)) return; await delay(30); } throw Error(label); };
  const click = label => js(`Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === ${JSON.stringify(label)} && button.getClientRects().length)?.click()`);
  ipcMain.handle('app:metadata', () => ({ name: 'Auto Poke RNG', version: 'test', platform: 'win32' }));
  registerPanelWindows({ getMainWindow: () => main, loadWindow: window => window.loadFile(path.join(root, 'dist/index.html')) });
  registerScriptFiles({ getMainWindow: () => main, rootDirectory: path.join(root, 'scripts') });
  devices = registerDevices({ ipcMain, getWindows: () => BrowserWindow.getAllWindows(), rootDirectory: path.join(root, 'scripts'), testMode: true });
  rng = registerRng({ ipcMain, getMainWindow: () => main, isAutomationBusy: () => devices.isAutomationBusy() });
  blink = registerBlink({ ipcMain, getMainWindow: () => main, getVideo: () => devices.getState().video, isAutomationBusy: () => devices.isAutomationBusy() });
  notifications = registerQQNotifications({ ipcMain, getMainWindow: () => main, safeStorage, nativeImage, userData });
  automation = registerAutomation({ ipcMain, getMainWindow: () => main, getWindows: () => BrowserWindow.getAllWindows(), devices, rng, blink, userData });
  await main.loadFile(path.join(root, 'dist/index.html'));
  main.showInactive();
  await until(`Boolean(document.querySelector('[aria-label^="切换游戏"]'))`, 'app ready');
  await js(`document.querySelector('[aria-label^="切换游戏"]').click()`);
  await until(`Boolean(document.querySelector('[role=menuitemradio]'))`, 'game picker');
  await js(`Array.from(document.querySelectorAll('[role=menuitemradio]')).find(item => item.textContent.includes('珍钻复刻')).click()`);
  await click('自动定点');
  await until(`Boolean(document.querySelector('.automation-group-sidebar'))`, 'configuration sidebar');
  assert.equal(await js(`document.querySelector('.automation-group-sidebar').textContent.includes('连续执行') || document.querySelector('.automation-group-sidebar').textContent.includes('继续执行')`), false);
  await js(`document.querySelector('[aria-label="新建自动流程配置"]').click()`);
  await until(`Boolean(document.querySelector('.automation-group-dialog input'))`, 'create dialog');
  await js(`(() => { const input = document.querySelector('.automation-group-dialog input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'骑拉帝纳定点'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await click('创建配置');
  await until(`document.querySelector('.automation-heading h2')?.textContent === '骑拉帝纳定点'`, 'new group active');
  await js(`document.querySelector('.automation-target-card').click()`);
  await until(`Boolean(document.querySelector('[aria-label="自动定点宝可梦"]'))`, 'target dialog');
  await js(`(() => { const input = document.querySelector('[aria-label="自动定点宝可梦"]'); input.value = 'Giratina'; input.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await until(`document.querySelector('.automation-target-dialog .automation-target-identity strong')?.textContent === '骑拉帝纳'`, 'target changed');
  await click('保存任务参数并返回');
  await until(`document.querySelector('.automation-target-card strong')?.textContent === '骑拉帝纳'`, 'target saved');
  const buttons = await js(`Array.from(document.querySelectorAll('.automation-group-select')).map(button => button.textContent.trim())`);
  assert.equal(buttons.length, 2);
  await js(`document.querySelectorAll('.automation-group-select')[0].click()`);
  await until(`document.querySelector('.automation-target-card strong')?.textContent === '草苗龟'`, 'first group restored');
  await until(`!document.querySelectorAll('.automation-group-select')[1].disabled`, 'group switch ready');
  await js(`document.querySelectorAll('.automation-group-select')[1].click()`);
  await until(`document.querySelector('.automation-target-card strong')?.textContent === '骑拉帝纳'`, 'second group restored');
  await delay(100);
  fs.writeFileSync(path.join(output, 'groups-wide.png'), (await main.webContents.capturePage()).toPNG());
  main.setSize(1060, 760);
  await delay(200);
  assert.equal(await js(`document.querySelector('.workspace-right-rail').getBoundingClientRect().top >= document.querySelector('.workspace-primary').getBoundingClientRect().bottom - 1`), true, 'monitor follows settings at compact widths');
  fs.writeFileSync(path.join(output, 'groups-compact.png'), (await main.webContents.capturePage()).toPNG());
  main.setSize(800, 700);
  await delay(200);
  assert.equal(await js(`document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1`), true, 'no horizontal viewport overflow');
  fs.writeFileSync(path.join(output, 'groups-narrow.png'), (await main.webContents.capturePage()).toPNG());
  await js(`document.querySelectorAll('.automation-group-menu-trigger')[1].click()`);
  await js(`Array.from(document.querySelectorAll('.automation-group-menu button')).find(button => button.textContent.includes('重命名')).click()`);
  await until(`Boolean(document.querySelector('.automation-group-dialog input'))`, 'rename dialog');
  await js(`(() => { const input=document.querySelector('.automation-group-dialog input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'骑拉帝纳闪光'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await click('保存名称');
  await until(`document.querySelector('.automation-heading h2')?.textContent === '骑拉帝纳闪光'`, 'group renamed');
  await js(`document.querySelectorAll('.automation-group-menu-trigger')[1].click()`);
  await js(`Array.from(document.querySelectorAll('.automation-group-menu button')).find(button => button.textContent.includes('删除配置')).click()`);
  await until(`Boolean(document.querySelector('.automation-group-delete'))`, 'delete dialog');
  await click('删除配置');
  await until(`document.querySelectorAll('.automation-group-select').length === 1`, 'group deleted');
  console.log('PASS: named groups persist independent targets; create, rename and delete work; no bottom execution buttons; rendered wide, compact and narrow views');
}).catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  clearTimeout(timer);
  await automation?.close(); notifications?.close();
  await Promise.allSettled([devices?.close(), blink?.close(), rng?.close()]);
  app.exit(process.exitCode || 0);
});
